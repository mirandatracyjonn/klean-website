# A small Markdown converter for the docs: headings, paragraphs, lists, tables, quotes, code blocks, and inline
# **bold**, *italic*, `code` and [links](url). Everything is escaped first.
def inline(text):
    text = html.escape(text, quote=False)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![*\w])\*([^*\s][^*]*)\*(?!\*)", r"<em>\1</em>", text)

    def link(m):
        label, href = m.group(1), m.group(2)
        href = re.sub(r"^(?:\.\./)?docs/([\w-]+)\.md", lambda d: "/" + {k[:-3]: v[0] for k, v in DOCS.items()}.get(d.group(1), d.group(1)) + ".html", href)
        safe = href if re.match(r"^(https?:|mailto:|/|#)", href) else "#"
        return f'<a href="{safe}">{label}</a>'
    return re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", link, text)


def markdown(source):
    out, para, lines, i = [], [], source.split("\n"), 0

    def flush():
        if para:
            out.append(f"<p>{inline(' '.join(para))}</p>")
            para.clear()

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if stripped.startswith("```"):
            flush()
            block = []
            i += 1
            while i < len(lines) and not lines[i].strip().startswith("```"):
                block.append(lines[i])
                i += 1
            out.append(f"<pre><code>{html.escape(chr(10).join(block))}</code></pre>")
        elif not stripped:
            flush()
        elif m := re.match(r"^(#{1,4})\s+(.*)$", stripped):
            flush()
            level = len(m.group(1))
            slug = re.sub(r"[^a-z0-9]+", "-", m.group(2).lower()).strip("-")
            out.append(f'<h{level} id="{slug}">{inline(m.group(2))}</h{level}>')
        elif stripped.startswith(">"):
            flush()
            quote = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                quote.append(lines[i].strip()[1:].strip())
                i += 1
            out.append(f"<blockquote><p>{inline(' '.join(quote))}</p></blockquote>")
            continue
        elif stripped.startswith("|"):
            flush()
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.match(r"^:?-{2,}:?$", c) for c in cells):
                    rows.append(cells)
                i += 1
            head, *body = rows
            out.append("<table><thead><tr>" + "".join(f"<th>{inline(c)}</th>" for c in head) + "</tr></thead><tbody>"
                       + "".join("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>" for r in body) + "</tbody></table>")
            continue
        elif re.match(r"^(\s*)([-*]|\d+\.)\s+", line):
            flush()
            ordered = bool(re.match(r"^\s*\d+\.", line))
            items = []
            while i < len(lines) and lines[i].strip():
                m = re.match(r"^(\s*)([-*]|\d+\.)\s+(.*)$", lines[i])
                if m and len(m.group(1)) < 2:
                    items.append(m.group(3))
                elif items:
                    items[-1] += " " + lines[i].strip()
                i += 1
            tag = "ol" if ordered else "ul"
            out.append(f"<{tag}>" + "".join(f"<li>{inline(it)}</li>" for it in items) + f"</{tag}>")
            continue
        else:
            para.append(stripped)
        i += 1
    flush()
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--app", default=str(ROOT.parent / "klean-app"), help="path to the klean-app repository")
    app = pathlib.Path(parser.parse_args().app).resolve()

    # Pages
    for src in sorted((ROOT / "pages").glob("*.html")):
        text = src.read_text()
        meta = dict(re.findall(r"^<!--\s*(\w+):\s*(.*?)\s*-->$", text, re.M))
        body = re.sub(r"^<!--\s*\w+:.*?-->\n", "", text, flags=re.M)
        scripts = [s for s in meta.get("scripts", "").split() if s]
        (ROOT / f"{src.stem}.html").write_text(layout(src.stem, meta.get("title", "Klean"), meta.get("description", PROMISE), body, scripts))

    # Docs from the app repo
    for file, (name, title, description) in DOCS.items():
        source = (app / "docs" / file).read_text()
        body = f'<article class="doc">\n{markdown(source)}\n</article>'
        (ROOT / f"{name}.html").write_text(layout(name, title, description, body))

    # Klean HQ
    hq_src, hq_out = app / "hq", ROOT / "hq"
    if hq_out.exists():
        shutil.rmtree(hq_out)
    shutil.copytree(hq_src, hq_out)
    print(f"Built {len(list((ROOT / 'pages').glob('*.html')))} pages, {len(DOCS)} documents, and Klean HQ.")


if __name__ == "__main__":
    main()
