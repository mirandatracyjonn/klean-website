#!/usr/bin/env python3
"""Builds klean.ph from source.

    python3 scripts/build.py [--app ../klean-app]

* pages/*.html (page bodies) → <name>.html at the site root, wrapped in the shared header, footer and security headers.
* The public literature in the app repo (docs/*.md) → terms.html, privacy.html, faq.html, help.html (User Handbook),
  manual.html (Super Admin Manual), hardware.html (Hardware Guide). The app repo's docs are the source of truth: never
  edit the generated pages, edit docs/ there and run this again.
* Klean HQ (the app repo's hq/) → hq/ (operator dashboard and machine simulator at klean.ph/hq/).
Never copies anything from the app repo's bible/ (the Bible is private).
"""
import argparse
import html
import pathlib
import re
import shutil

ROOT = pathlib.Path(__file__).resolve().parent.parent
SUPABASE = "https://allxvwnohkibfjbpoxvu.supabase.co"
TAGLINE = "Keep it simple. Keep it Klean."
